import {mkdir,copyFile,readdir,readFile,writeFile} from 'node:fs/promises';
import {copyWorkboxLibraries,injectManifest} from 'workbox-build';
await mkdir('dist/vendor/ocr/core',{recursive:true});
await copyFile('node_modules/dexie/dist/dexie.mjs','dist/vendor/dexie.mjs');
await copyFile('node_modules/dexie/LICENSE','dist/vendor/dexie-LICENSE');
await copyFile('node_modules/fuse.js/dist/fuse.min.mjs','dist/vendor/fuse.mjs');
await copyFile('node_modules/fuse.js/LICENSE','dist/vendor/fuse-LICENSE');
await copyFile('node_modules/@ericblade/quagga2/dist/quagga.min.js','dist/vendor/quagga.min.js');
await copyFile('node_modules/@zxing/browser/umd/zxing-browser.min.js','dist/vendor/zxing-browser.min.js');
await copyFile('node_modules/@zxing/browser/LICENSE','dist/vendor/zxing-LICENSE');
for(const f of ['tesseract.min.js','worker.min.js'])await copyFile('node_modules/tesseract.js/dist/'+f,'dist/vendor/ocr/'+f);
for(const f of await readdir('node_modules/tesseract.js-core'))if(/\.(js|wasm)$/.test(f))await copyFile('node_modules/tesseract.js-core/'+f,'dist/vendor/ocr/core/'+f);
for(const [pkg,name] of [['@ericblade/quagga2','quagga'],['tesseract.js','tesseract'],['tesseract.js-core','tesseract-core'],['workbox-sw','workbox']])await copyFile('node_modules/'+pkg+(pkg==='tesseract.js'?'/LICENSE.md':'/LICENSE'),'dist/vendor/'+name+'-LICENSE');
const dir=await copyWorkboxLibraries('dist');
await copyFile('node_modules/workbox-sw/build/workbox-sw.js','dist/workbox-sw.js');
let source=await readFile('scripts/service-worker.js','utf8');
source=source.replace('__WORKBOX_DIR__',dir);
await writeFile('scripts/sw-generated.js',source);
const result=await injectManifest({swSrc:'scripts/sw-generated.js',swDest:'dist/sw.js',globDirectory:'dist',globPatterns:['offline.html','offline.js','offline-draft.js','offline-store.js','print-list.js','lists-domain.js','vendor/dexie.mjs','catalog-cache.js','lookup.js','domain.js','vendor/fuse.mjs','stock.js','style.css','assets/logo.png'],maximumFileSizeToCacheInBytes:2000000});
console.log('Offline: '+result.count+' arquivos, '+result.size+' bytes');
for(const warning of result.warnings)console.warn(warning);
