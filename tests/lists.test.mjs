test('ordenação numérica e alfabética preserva os itens originais',()=>{
 const items=[{id:'1',product_name:'Zebra',quantity:2},{id:'2',product_name:'Água',quantity:10},{id:'3',product_name:'Borracha',quantity:1}];
 assert.deepEqual(sortListItems(items,'name-asc').map(i=>i.id),['2','3','1']);
 assert.deepEqual(sortListItems(items,'name-desc').map(i=>i.id),['1','3','2']);
 assert.deepEqual(sortListItems(items,'quantity-asc').map(i=>i.quantity),[1,2,10]);
 assert.deepEqual(sortListItems(items,'quantity-desc').map(i=>i.quantity),[10,2,1]);
 assert.equal(items[0].id,'1');
 assert.equal(canMarkReady({status:'em_separacao',items:[{picked:true},{unavailable:true}]}),true);
 assert.equal(canMarkReady({status:'em_separacao',items:[{unavailable:true},{picked:false}]}),true);
 assert.equal(canMarkReady({status:'em_separacao',items:[{unavailable:true}]}),true);
});

test('marcas são agrupadas sem esconder itens e desconhecidas ficam no final',()=>{
 assert.equal(itemBrand({product_name:'Papel VMP A4'}),'VMP');
 assert.equal(itemBrand({product_name:'Caneta master-print azul'}),'Master Print');
 assert.equal(itemBrand({product_name:'Caneta MASTERPRINT'}),'Master Print');
 assert.equal(itemBrand({product_name:'Borracha mercur'}),'Mercur');
 assert.equal(itemBrand({product_name:'Produto FUTURO'}),'Futuro');
 assert.equal(itemBrand({product_name:'Produto VMPX'}),'');
 const items=['Zebra VMP','Sem marca','Borracha Mercur','Caneta Futuro','Azul VMP'].map((product_name,id)=>({id,product_name}));
 assert.deepEqual(sortListItems(items,'brand').map(i=>i.product_name),['Caneta Futuro','Borracha Mercur','Azul VMP','Zebra VMP','Sem marca']);
 assert.equal(items[0].product_name,'Zebra VMP');
});

